def seed_database(db):
    """최초 실행 시 목업 데이터를 DB에 삽입"""
    from app.models import Restaurant, Menu, CrowdByHour
    if db.query(Restaurant).count() > 0:
        return  # 이미 데이터 있음

    for data in MOCK_RESTAURANTS:
        menus = data.pop("menus")
        crowd = data.pop("crowd_by_hour")

        # 리스트를 JSON 문자열로 변환
        data["tags"] = json.dumps(data["tags"], ensure_ascii=False)
        data["features"] = json.dumps(data["features"], ensure_ascii=False)
        if "meal_times" in data:
            data["meal_times"] = json.dumps(data["meal_times"], ensure_ascii=False)

        restaurant = Restaurant(**data)
        db.add(restaurant)
        db.flush()

        for m in menus:
            db.add(Menu(restaurant_id=restaurant.id, **m))

        for c in crowd:
            db.add(CrowdByHour(
                restaurant_id=restaurant.id,
                hour_label=c["hour_label"],
                hour_value=c.get("hour_value"),
                crowd_ratio=c["crowd_ratio"],
            ))

    db.commit()
    print("✅ Mock 데이터 삽입 완료 (8개 식당)")
